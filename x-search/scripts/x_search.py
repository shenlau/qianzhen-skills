#!/usr/bin/env python3
"""x_search.py — complete read-only X (Twitter) client using the logged-in
browser session from the x-refresh project.

Covers the everyday "X in a browser" flows:
  search      search tweets/users (Top/Latest/People/Media/Lists)
  home        For You / Following timelines
  tweet       open a post and read its replies (TweetDetail)
  user        a profile's posts / replies / media / likes
  bookmarks   your saved posts
  likes       your liked posts

Credentials/proxy come from ~/x-refresh/config.json. Zero third-party
dependencies; every request goes through `curl` (robust retries behind flaky
proxies) via the configured proxy.

How it survives X's anti-hardcoding measures:
  * GraphQL queryIds rotate every few weeks  -> extracted LIVE from x.com's
    current JavaScript: main.js first, then the lazily-loaded chunks whose
    index is embedded in the home page (webpack runtime `.u=e=>`), swept in
    parallel, early-stopping once every op we need is found (per-op feature
    switches come from the same bundle snippets). Cached 24h in
    ~/.cache/x-search/state.json; on a 404 the cache is dropped, everything
    is re-extracted once, and the request retried.
  * SearchTimeline (search), UserTweetsAndReplies and Followers are extra
    gated: they require a per-request `x-client-transaction-id` header —
    single-use, generated by an algorithm ported verbatim (MIT) from
    iSarabjitDhiman/XClientTransaction, with inputs derived from the home
    page (verification meta, loading-anim SVG frames, ondemand.s indices).
    This script only calls SearchTimeline among the gated ops, and uses the
    ungated UserRepliesTimeline for profile replies.

Usage:
  x_search.py "DLSS 5"                          # legacy shorthand -> search
  x_search.py search "DLSS 5" --latest --pages 2
  x_search.py home --following -n 30
  x_search.py tweet https://x.com/user/status/123...
  x_search.py user nvidia --media
  x_search.py bookmarks --json
  x_search.py likes

Exit codes:
  0 ok            1 bad usage        2 auth/config problem
  3 runtime extraction failed (X rebuilt its client — re-port needed)
  4 X rejected the generated transaction-id (algorithm rotted)
  5 rate-limited (429)   6 request/pagination failure
"""
