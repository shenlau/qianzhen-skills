def gql_call(http, cfg, runtime, op, variables, cursor=None, verbose=False):
    """One GraphQL request. Mint a txid only for the gated ops."""
    variables = dict(variables)
    if cursor:
        variables["cursor"] = cursor
    qid = runtime["ops"][op]
    path = f"/i/api/graphql/{qid}/{op}"
    features = dict(runtime["features"].get(op) or next(iter(runtime["features"].values())))
    qs = {
        "variables": json.dumps(variables, separators=(",", ":")),
        "features": json.dumps(features, separators=(",", ":")),
    }
    toggles = FIELD_TOGGLES.get(op)
    if toggles is not None:
        qs["fieldToggles"] = json.dumps(toggles, separators=(",", ":"))
    url = f"https://x.com{path}?" + urllib.parse.urlencode(qs)
    txid = None
    if op in GATED_OPS:
        txid = mint_transaction_id(runtime["key_bytes"], runtime["animation_key"], "GET", path)
    status, headers, body = http.fetch(url, gql=cfg, txid=txid)
    if verbose:
        print(f"[x-search] GET {op} ({len(json.dumps(variables))}B vars) "
              f"txid={'yes' if txid else 'no'} -> HTTP {status}", file=sys.stderr)
    if status == 200:
        try:
            return json.loads(body), status, headers
        except json.JSONDecodeError:
            return None, -1, headers
    return None, status, headers


def paginate(http, cfg, runtime, op, variables, parse, pages, verbose=False):
    """Request `op` page-by-page via the bottom cursor. `parse` gets the JSON
    payload and returns (items, users, next_cursor). Resilient to the worst
    mid-run failure modes: 404 self-heal (re-extract once), 429 exit 5."""
    items_all, users_all = [], []
    cursor = None
    page = 0
    retried = False
    while page < pages:
        payload, status, headers = gql_call(http, cfg, runtime, op, variables,
                                            cursor=cursor, verbose=verbose)
        if payload is None:
            if status == 429:
                reset = headers.get("x-rate-limit-reset")
                hint = ""
                try:
                    hint = ("; bucket resets at "
                            + time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(int(reset)))) if reset else ""
                except Exception:
                    pass
                die(5, f"rate-limited by X (429) on {op}{hint} "
                      f"[limit {headers.get('x-rate-limit-limit')}, "
                      f"remaining {headers.get('x-rate-limit-remaining')}] — "
                      f"fewer --pages or retry later")
            if status in (401, 403):
                die(2, f"X rejected the credentials (HTTP {status}) — update "
                      f"auth_token/ct0 in the x-refresh config")
            if status == 404 and not retried:
                retried = True  # only once, across the whole pagination
                if verbose:
                    print("[x-search] 404 — re-extracting runtime & retrying once…", file=sys.stderr)
                try:
                    runtime_new = extract_runtime(http, {"auth_token": cfg["auth_token"],
                                                        "ct0": cfg["ct0"]}, verbose=verbose)
                except RuntimeError:
                    # fall through to the rejection message below
                    pass
                else:
                    runtime.clear()
                    runtime.update(runtime_new)
                    continue
            if status == 404:
                die(4, f"X returned 404 for {op} — the queryId/algorithm has "
                      f"likely rotted after an X client redeploy. Re-port needed "
                      f"(https://github.com/iSarabjitDhiman/XClientTransaction "
                      f"for the txid generator)")
            die(6, f"X request failed for {op} (HTTP {status})")
        page += 1
        if "errors" in payload and not payload.get("data"):
            die(6, f"X API errors: {json.dumps(payload['errors'][:3], ensure_ascii=False)}")
        try:
            items, users, next_cursor = parse(payload)
        except Exception as ex:
            die(6, f"failed to parse the {op} response: {ex}")
        items_all.extend(items)
        users_all.extend(users)
        if not next_cursor:
            break
        cursor = next_cursor
        if page < pages:
            time.sleep(2.5)  # light pacing between pages
    return items_all, users_all, page


