def find_instructions(payload, depth=0):
    """Recursively locate the first `instructions` list in the payload. Every
    timeline-flavoured op nests it under a different root; this keeps the
    parser resilient to X renaming those roots."""
    if depth > 6 or not isinstance(payload, dict):
        return []
    for k, v in payload.items():
        if k == "instructions" and isinstance(v, list):
            return v
        found = find_instructions(v, depth + 1)
        if found:
            return found
    return []


def parse_user(u):
    core = u.get("core", {}) or {}
    legacy = u.get("legacy", {}) or {}
    return {
        "screen_name": core.get("screen_name") or u.get("rest_id", ""),
        "name": core.get("name", ""),
        "verified": bool(u.get("is_blue_verified")),
        "description": (u.get("profile_bio", {}) or {}).get("description", "")
                        or legacy.get("description", ""),
        "location": ((u.get("location", {}) or {}).get("location"))
                    or legacy.get("location", ""),
        "followers": legacy.get("followers_count"),
        "following": legacy.get("friends_count"),
        "tweets": legacy.get("statuses_count"),
        "rest_id": u.get("rest_id"),
    }


def parse_tweet(tr):
    if tr.get("__typename") == "TweetWithVisibilityResults":
        tr = tr.get("tweet", {})
    legacy = tr.get("legacy", {}) or {}
    if not legacy and tr.get("tweet", {}):
        tr = tr["tweet"]
        legacy = tr.get("legacy", {}) or {}
    note = ((tr.get("note_tweet", {}) or {})
            .get("note_tweet_results", {}).get("result", {}) or {})
    text = note.get("text") or legacy.get("full_text", "")
    user = (tr.get("core", {}) or {}).get("user_results", {}).get("result", {}) or {}
    udata = parse_user(user)
    try:
        dt = parsedate_to_datetime(legacy.get("created_at", ""))
        created_iso = dt.isoformat()
    except Exception:
        dt = None
        created_iso = legacy.get("created_at", "")
    views = tr.get("views", {}).get("count")
    return {
        "id": tr.get("rest_id"),
        "created_at": legacy.get("created_at", ""),
        "iso": created_iso,
        "text": text,
        "author": udata,
        "url": f"https://x.com/{udata['screen_name']}/status/{tr.get('rest_id', '')}",
        "views": int(views) if views else None,
        "likes": legacy.get("favorite_count"),
        "retweets": legacy.get("retweet_count"),
        "replies": legacy.get("reply_count"),
        "quotes": legacy.get("quote_count"),
        "bookmarks": legacy.get("bookmark_count"),
        "lang": legacy.get("lang"),
        "is_retweet": "RT @" in legacy.get("full_text", "")[:5],
        "sensitive": bool(legacy.get("possibly_sensitive")),
        "in_reply_to": legacy.get("in_reply_to_status_id_str"),
    }


def parse_entries(payload, verbose=False):
    """Get (tweets, users, next_cursor) from any instructions list. Handles
    plain items, cursor entries and the conversation modules TweetDetail uses."""
    instructions = find_instructions(payload)
    tweets, users, next_cursor = [], [], None
    for ins in instructions:
        for e in ins.get("entries", []):
            eid = e.get("entryId", "")
            content = e.get("content", {}) or {}
            if content.get("entryType") == "TimelineTimelineCursor" or eid.startswith("cursor"):
                if content.get("cursorType") == "Bottom" or eid.startswith("cursor-bottom"):
                    next_cursor = content.get("value")
                continue
            if content.get("entryType") == "TimelineTimelineModule":
                for item in content.get("items", []):
                    ic = (item.get("itemContent", {}) or {}).get("itemContent", {}) \
                         or (item.get("item", {}) or {}).get("itemContent", {}) \
                         or item.get("itemContent", {}) or {}
                    tr = (ic.get("tweet_results", {}) or {}).get("result")
                    if tr:
                        tweets.append(parse_tweet(tr))
                continue
            ic = content.get("itemContent", {}) or {}
            if isinstance(ic.get("tweet_results"), dict) and ic["tweet_results"].get("result"):
                tweets.append(parse_tweet(ic["tweet_results"]["result"]))
            elif isinstance(ic.get("user_results"), dict) and ic["user_results"].get("result"):
                users.append(parse_user(ic["user_results"]["result"]))
            elif verbose:
                print(f"[x-search] skipped entry {eid or content.get('entryType')}",
                      file=sys.stderr)
    seen, dedup_t = set(), []
    for t in tweets:
        if t["id"] not in seen:
            seen.add(t["id"])
            dedup_t.append(t)
    seen, dedup_u = set(), []
    for u in users:
        key = u["screen_name"]
        if key not in seen:
            seen.add(key)
            dedup_u.append(u)
    return dedup_t, dedup_u, next_cursor


