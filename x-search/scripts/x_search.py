def _extract_tweet_id(arg):
    m = re.search(r"(?:status/|statuses/)(\d{5,25})", arg)
    if m:
        return m.group(1)
    if re.fullmatch(r"\d{5,25}", arg):
        return arg
    die(1, f"could not read a tweet id from {arg!r} — pass a "
           f"https://x.com/<user>/status/<id> URL or the bare id")


def cmd_tweet(http, cfg, runtime, args):
    tweet_id = _extract_tweet_id(args.tweet)
    variables = {
        "focalTweetId": tweet_id,
        "with_rux_injections": False,
        "rankingMode": "Relevance",
        "includePromotedContent": True,
        "withCommunity": True,
        "withQuickPromoteEligibilityTweetFields": True,
        "withBirdwatchNotes": True,
        "withVoice": True,
    }
    tweets, users, page = paginate(http, cfg, runtime, "TweetDetail",
                                   variables, parse_entries, args.pages,
                                   verbose=args.verbose)
    focal = next((t for t in tweets if t["id"] == tweet_id), None)
    # Order the way a browser shows: ancestors-of-focal (root-first), focal, then
    # every other tweet in the conversation as replies.
    ancestors, replies_ordered = [], []
    if focal:
        chain = {t["id"]: t for t in tweets if t["id"] != focal["id"]}
        cursor_id = focal.get("in_reply_to")
        while cursor_id and cursor_id in chain:
            t = chain.pop(cursor_id)
            ancestors.insert(0, t)
            cursor_id = t.get("in_reply_to")
        order = {t["id"]: i for i, t in enumerate(tweets)}
        replies_ordered = sorted(chain.values(), key=lambda t: order.get(t["id"], 0))
    else:
        replies_ordered = tweets
    if args.json:
        print(json.dumps({"tweet_id": tweet_id, "focal": focal,
                          "ancestors": ancestors, "replies": replies_ordered,
                          "pages_fetched": page},
                         ensure_ascii=False, indent=1))
        return
    print(f'X thread — focal: {tweet_id}  pages: {page}/{args.pages}  '
          f'posts: {len(tweets)} (focal + {len(ancestors)} ancestors + {len(replies_ordered)} replies)')
    if ancestors:
        print("── thread (背景) " + "─" * 30)
        print_tweets(ancestors, None)
    if focal:
        print("── 主帖 " + "─" * 40)
        print_tweets([focal])
    if replies_ordered:
        print("── 回复 " + "─" * 41)
        print_tweets(replies_ordered)
    if not tweets:
        print("(no results — is the tweet id correct? deleted/private tweets return nothing)")


def _resolve_user_id(http, cfg, runtime, handle, verbose=False):
    handle = handle.lstrip("@")
    variables = {"screen_name": handle, "withSafetyModeUserFields": True}
    payload, status, headers = gql_call(http, cfg, runtime, "UserByScreenName",
                                        variables, verbose=verbose)
    if payload is None:
        die(6 if status != 404 else 4, f"UserByScreenName failed (HTTP {status}) for @{handle}")
    u = payload.get("data", {}).get("user", {}).get("result", {})
    rest_id = u.get("rest_id")
    if not rest_id:
        if u.get("__typename") == "UserUnavailable":
            die(1, f"@{handle} is unavailable ({u.get('reason', 'suspended/protected')})")
        die(6, f"could not resolve @{handle} to a user id")
    return rest_id, parse_user(u)


