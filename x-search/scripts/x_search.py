def local_time(iso):
    try:
        return parsedate_to_datetime(iso).astimezone().strftime("%Y-%m-%d %H:%M")
    except Exception:
        try:
            return datetime.fromisoformat(iso).astimezone().strftime("%Y-%m-%d %H:%M")
        except Exception:
            return ""


def relative_time(iso):
    try:
        try:
            dt = parsedate_to_datetime(iso)
        except Exception:
            dt = datetime.fromisoformat(iso)
        diff = (datetime.now().astimezone() - dt).total_seconds()
        if diff < 3600:
            return f"{max(int(diff // 60), 0)}m ago" if diff < 3600 else ""
        if diff < 86400:
            return f"{int(diff // 3600)}h ago"
        return f"{int(diff // 86400)}d ago"
    except Exception:
        return ""


def print_tweets(tweets, title=None):
    if title:
        print(title)
    for i, t in enumerate(tweets, 1):
        a = t["author"]
        tick = " ✔" if a["verified"] else ""
        rel = relative_time(t["iso"])
        local = local_time(t["iso"])
        stamp = f"{local} ({rel})" if rel or local else ""
        reply_info = ""
        if t.get("in_reply_to"):
            reply_info = f"  ↩ reply"  # in_reply_to_status_id; replyee unknown w/o extra lookup
        print(f'{i}. {a["name"]} (@{a["screen_name"]}){tick}  {stamp}{reply_info}')
        print(f'   {t["url"]}')
        print(f'   {t["text"]}')
        stats = []
        for label, v in (("views", t["views"]), ("likes", t["likes"]),
                         ("RTs", t["retweets"]), ("replies", t["replies"]),
                         ("quotes", t["quotes"]), ("bookmarks", t["bookmarks"])):
            if v:
                stats.append(f"{label} {v}")
        if t["lang"]:
            stats.append(f"lang={t['lang']}")
        if stats:
            print("   · " + "  ".join(stats))
        print()


def print_users(users):
    for i, u in enumerate(users, 1):
        tick = " ✔" if u["verified"] else ""
        extras = []
        if u.get("followers") is not None:
            extras.append(f"followers {u['followers']}")
        if u.get("location"):
            extras.append(u["location"])
        line = f'{i}. {u["name"]} (@{u["screen_name"]}){tick}' + \
               (f"  [{', '.join(extras)}]" if extras else "")
        print(line)
        if u["description"]:
            print(f'   {u["description"]}')
        print()


